const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const root = path.join(__dirname, '..');
const html = fs.readFileSync(path.join(root, 'index.html'), 'utf8');
const js = fs.readFileSync(path.join(root, 'site.js'), 'utf8');
const ids = [...html.matchAll(/\bid="([^"]+)"/g)].map(m => m[1]);
assert.equal(ids.length, new Set(ids).size, 'IDs must be unique');
for (const [,id] of html.matchAll(/href="#([^"]+)"/g)) assert(ids.includes(id), 'Missing anchor '+id);
for (const [,src] of html.matchAll(/(?:src|href)="([^"#:]+)"/g)) {
  if (/^(https?:|mailto:|tel:)/.test(src)) continue;
  assert(fs.existsSync(path.join(root, src.split('?')[0].replace(/^\//,''))), 'Missing asset '+src);
}
const schema = JSON.parse(html.match(/<script type="application\/ld\+json">([\s\S]*?)<\/script>/)[1]);
assert.equal(schema['@graph'][0].url, 'https://playtheusualsuspects.com/');
const cards = [...html.matchAll(/<article class="show-card" id="([^"]+)" data-start="([^"]+)" data-end="([^"]+)">([\s\S]*?)<\/article>/g)].map(m => ({
  id:m[1],dataset:{start:m[2],end:m[3]},hidden:false,
  querySelector(selector) { return {textContent: selector === '.show-venue' ? 'Test venue' : 'Saturday · 8:00 PM – 11:00 PM · Address'}; }
}));
assert.equal(cards.length, 3);
cards.forEach(c=>assert(Date.parse(c.dataset.end)>Date.parse(c.dataset.start)));
const frankfort = cards.find(c=>c.id==='show-7');
const frankfortEvent = schema['@graph'].find(e=>e['@id']==='https://playtheusualsuspects.com/#show-7');
assert.equal(frankfortEvent.startDate, frankfort.dataset.start);
assert.equal(frankfortEvent.endDate, frankfort.dataset.end);
const hero = {replaceChildren(){this.children=[];},append(...items){this.children=items;}};
const featureTag = html.match(/<section class="featured-shows"[^>]+>/)[0];
const featured = {dataset:Object.fromEntries([...featureTag.matchAll(/data-([\w-]+)="([^"]+)"/g)].map(([,key,value])=>[key.replace(/-([a-z])/g,(_,c)=>c.toUpperCase()),value])),hidden:false};
const context = {Intl,Date,document:{querySelector:()=>featured,querySelectorAll:selector=>selector.includes('show-card') ? cards : [],getElementById:()=>hero,createElement:()=>({})}};
vm.createContext(context);
vm.runInContext(js.slice(js.indexOf('function refreshShows'),js.indexOf('refreshShows();')),context);
context.refreshShows(Date.parse('2026-11-18T18:00:00Z'));
assert.equal(hero.href,'#show-5');
assert.equal(hero.children[0].textContent,'Next show');
assert.equal(featured.hidden,false);
assert(!/chili|Farm2Veteran|2026-11-14|2026-10-03/i.test(html), 'Retire expired promotion from the HTML, not only with JavaScript');
context.refreshShows(Date.parse('2027-01-01T00:00:00Z'));
assert.equal(hero.href,'#show-6');
assert.equal(hero.children[0].textContent,'Next show');
context.refreshShows(Date.parse('2027-01-31T02:00:00Z'));
assert.equal(hero.children[0].textContent,'On stage now');
context.refreshShows(Date.parse('2027-01-31T05:30:00Z'));
assert.equal(hero.href,'#show-7');
assert.equal(hero.children[0].textContent,'Next show');
context.refreshShows(Date.parse('2027-04-04T00:29:59Z'));
assert.equal(hero.children[0].textContent,'Next show');
context.refreshShows(Date.parse('2027-04-04T00:30:00Z'));
assert.equal(hero.href,'#show-7');
assert.equal(hero.children[0].textContent,'On stage now');
assert.equal(frankfort.hidden,false);
context.refreshShows(Date.parse('2027-04-04T03:30:00Z'));
assert.equal(hero.href,'#book');
assert(cards.every(c=>c.hidden));
// December 5 is CST: 8 PM local is December 6 at 02:00 UTC.
const digits = Object.fromEntries(['days','hours','minutes','seconds'].map(unit=>[unit,{}]));
const clock = {hidden:true, querySelector(selector){return digits[selector.match(/"([^"']+)"/)[1]];}};
const countdownStatus = {};
const featureNav = {hidden:false};
context.document.querySelectorAll = selector => selector.includes('show-card') ? cards : [featureNav];
context.document.getElementById = id => id === 'hero-next' ? hero : id === 'show-countdown' ? clock : countdownStatus;
vm.runInContext(js.slice(js.indexOf('function refreshCountdown'),js.indexOf('refreshCountdown();')),context);
context.refreshCountdown(Date.parse('2026-12-05T01:00:00Z'));
assert.equal(clock.hidden,false);
assert.equal(digits.days.textContent,'01');
assert.equal(digits.hours.textContent,'01');
assert.equal(countdownStatus.textContent,'We take the stage in');
assert.equal(featureNav.hidden,false);
context.refreshCountdown(Date.parse('2026-12-06T01:59:59Z'));
assert.equal(digits.seconds.textContent,'01');
assert.equal(featured.hidden,false);
context.refreshCountdown(Date.parse('2026-12-06T02:00:00Z'));
assert.equal(clock.hidden,true);
assert.equal(featured.hidden,false);
assert.equal(countdownStatus.textContent,'On stage now · until 11:00 PM Central');
assert.equal(hero.children[0].textContent,'On stage now');
assert.equal(hero.href,'#show-5');
context.refreshCountdown(Date.parse('2026-12-06T04:59:59Z'));
assert.equal(featured.hidden,false);
assert.equal(hero.href,'#show-5');
context.refreshCountdown(Date.parse('2026-12-06T05:00:00Z'));
assert.equal(featured.hidden,true);
assert.equal(featureNav.hidden,true);
assert.equal(hero.href,'#show-6');
const december = schema['@graph'].find(e=>e['@id']==='https://playtheusualsuspects.com/#show-5');
assert.equal(december.startDate,featured.dataset.featuredStart);
assert.equal(december.endDate,featured.dataset.featuredEnd);
for (const card of cards) {
  const event = schema['@graph'].find(e=>e['@id']==='https://playtheusualsuspects.com/#'+card.id);
  assert.equal(event.startDate,card.dataset.start);
  assert.equal(event.endDate,card.dataset.end);
}
